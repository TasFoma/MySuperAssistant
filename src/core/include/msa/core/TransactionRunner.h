#pragma once

#include <functional>

namespace msa::core {

/// @brief Граница атомарной операции над общим хранилищем без знания SQL и Qt.
class TransactionRunner {
public:
    /// @brief Освобождает реализацию.
    virtual ~TransactionRunner();
    /// @brief Синхронно вызывает operation ровно один раз, фиксирует только нормальный возврат.
    /// Любое исключение, включая ошибку фиксации, требует отката и пробрасывается.
    /// Callback сообщает отказ исключением, возвращаемые статусы не анализируются.
    /// Все участвующие репозитории должны принадлежать этому исполнителю.
    /// При невозможности отката реализация запрещает дальнейшую работу с хранилищем.
    /// Внешние вызовы LLM/сети внутри операции недопустимы.
    virtual void transaction(const std::function<void()>& operation) = 0;
};

}  // namespace msa::core

